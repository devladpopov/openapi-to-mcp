import type { AuthMode, GenerateOptions, SecurityScheme } from "../types.js";
import { GENERATOR_VERSION, defaultBaseUrl, slugify } from "./util.js";

export function renderConfig(opts: GenerateOptions): string {
	const config = {
		serverName: opts.serverName,
		serverVersion: opts.spec.info?.version ? String(opts.spec.info.version) : "0.1.0",
		baseUrl: defaultBaseUrl(opts.spec),
		transport: opts.transport,
		auth: authConfig(opts),
		target: opts.target ?? "generic",
		nullAsAbsent: opts.target === "openai",
	};
	return `// Generated by openapi-mcp-codegen ${GENERATOR_VERSION}. Environment variables override these defaults.

import type { RuntimeConfig } from "./types.js";

export const CONFIG: RuntimeConfig = ${JSON.stringify(config, null, "\t")};
`;
}

function schemes(opts: GenerateOptions): SecurityScheme[] {
	return Object.values(opts.spec.components?.securitySchemes ?? {}).filter((s) => s && typeof s === "object");
}

function authConfig(opts: GenerateOptions): Record<string, unknown> {
	const auth: Record<string, unknown> = { mode: opts.auth };
	if (opts.auth === "api-key") {
		const s = schemes(opts).find((x) => x.type === "apiKey");
		auth.apiKeyName = s?.name ?? "X-API-Key";
		auth.apiKeyIn = s?.in ?? "header";
	}
	if (opts.auth === "oauth2" || opts.auth === "oauth2-auth-code") {
		const s = schemes(opts).find((x) => x.type === "oauth2");
		const flow =
			opts.auth === "oauth2-auth-code"
				? s?.flows?.authorizationCode
				: (s?.flows?.clientCredentials ?? s?.flows?.client_credentials);
		if (flow?.authorizationUrl) auth.authorizationUrl = flow.authorizationUrl;
		if (flow?.tokenUrl) auth.tokenUrl = flow.tokenUrl;
		const scopes = Object.keys(flow?.scopes ?? {});
		if (scopes.length) auth.scopes = scopes.slice(0, 50).join(" ");
	}
	return auth;
}

const AUTH_ENV: Record<AuthMode, string[]> = {
	none: [],
	"api-key": ["API_KEY=your-api-key-here", "# API_KEY_PREFIX=Token   # optional scheme prefix, e.g. 'Token' or 'Bearer'"],
	bearer: ["API_TOKEN=your-bearer-token-here"],
	basic: ["API_USERNAME=", "API_PASSWORD="],
	oauth2: ["OAUTH_CLIENT_ID=", "OAUTH_CLIENT_SECRET=", "OAUTH_TOKEN_URL=", "# OAUTH_SCOPES="],
	"oauth2-auth-code": [
		"OAUTH_CLIENT_ID=",
		"OAUTH_CLIENT_SECRET=",
		"OAUTH_AUTH_URL=",
		"OAUTH_TOKEN_URL=",
		"OAUTH_SCOPES=",
		"OAUTH_REDIRECT_PORT=8976",
		"# OAUTH_ACCESS_TOKEN=   # skip the browser flow with an existing token",
	],
};

export function renderEnvExample(opts: GenerateOptions): string {
	const lines = [`# Generated by openapi-mcp-codegen ${GENERATOR_VERSION}`, ""];
	lines.push(`API_BASE_URL=${defaultBaseUrl(opts.spec) || "https://api.example.com"}`);
	lines.push(...AUTH_ENV[opts.auth]);
	lines.push(
		"",
		"# Optional",
		"# API_EXTRA_HEADERS={\"X-Custom\":\"value\"}   # sent with every request",
		"# API_TIMEOUT_MS=30000",
		"# MAX_RESPONSE_CHARS=100000",
		"# MCP_READ_ONLY=true                          # expose GET tools only",
		"# MCP_TOOLS_INCLUDE=pets*,users               # names, tags or globs",
		"# MCP_TOOLS_EXCLUDE=delete*",
		"# MCP_TRANSPORT=streamable-http               # PORT=3000",
		"# HOST=127.0.0.1                             # set 0.0.0.0 to expose, together with:",
		"# MCP_AUTH_TOKEN=                             # clients send Authorization: Bearer <token>",
		"# MCP_ALLOWED_HOSTS=mcp.example.com           # accepted Host/Origin besides localhost",
	);
	if (opts.webhooks?.length) {
		lines.push(
			"",
			"# Webhooks",
			"# WEBHOOK_PORT=8787",
			"# WEBHOOK_HOST=127.0.0.1",
			"# WEBHOOK_PUBLIC_URL=https://your-tunnel.example.com/webhooks",
			"# WEBHOOK_SECRET=                             # verify HMAC signatures (GitHub, Stripe, Slack, generic)",
			"# WEBHOOK_TOLERANCE_SECONDS=300               # reject older signed timestamps (replays)",
			"# WEBHOOK_BUFFER_BYTES=52428800               # cap on buffered event payloads",
		);
	}
	return `${lines.join("\n")}\n`;
}

export function renderReadme(opts: GenerateOptions): string {
	const slug = slugify(opts.serverName) || "mcp-server";
	const env: Record<string, string> = { API_BASE_URL: defaultBaseUrl(opts.spec) || "https://api.example.com" };
	for (const line of AUTH_ENV[opts.auth]) {
		if (line.startsWith("#")) continue;
		const [k, v] = line.split("=");
		env[k] = v || "...";
	}
	const envJson = JSON.stringify(env, null, 2).replace(/\n/g, "\n      ");
	const envToml = Object.entries(env)
		.map(([k, v]) => `${k} = ${JSON.stringify(v)}`)
		.join(", ");
	const envFlags = Object.entries(env)
		.map(([k, v]) => `-e ${k}=${v}`)
		.join(" ");

	const rows = opts.tools
		.slice(0, 300)
		.map((t) => `| \`${t.name}\` | ${t.meta.method} \`${t.meta.path}\` | ${escapeCell(t.title ?? t.description).slice(0, 100)} |`);
	if (opts.tools.length > rows.length) rows.push(`| ... | ${opts.tools.length - rows.length} more | see tools.json |`);

	const webhookSection = opts.webhooks?.length
		? `
## Webhooks

This API declares ${opts.webhooks.length} webhook event(s). The server runs a receiver on \`http://localhost:8787/webhooks\` (stdio mode, \`WEBHOOK_PORT\`) or on \`/webhooks\` of the HTTP server (streamable-http mode). Point the provider at \`<public url>/webhooks/<event>\` through a tunnel (ngrok, cloudflared) and set \`WEBHOOK_PUBLIC_URL\`. Set \`WEBHOOK_SECRET\` to verify signatures.

The model reads events with \`webhooks_list_types\`, \`webhooks_get_events\` and \`webhooks_wait_for_event\`. The wait tool supports MCP Tasks, so task-aware clients get a handle immediately and collect the event later. Clients can also subscribe to the \`webhook://events\` resource.

| Event | Receiver path |
|---|---|
${opts.webhooks.map((w) => `| \`${w.name}\` | \`/webhooks/${w.slug}\` |`).join("\n")}
`
		: "";

	return `# ${opts.serverName} MCP server

Generated by [openapi-mcp-codegen](https://github.com/devladpopov/openapi-to-mcp) ${GENERATOR_VERSION} from the ${opts.spec.info?.title ?? ""} OpenAPI spec (schema target: \`${opts.target ?? "generic"}\`).

## Run

\`\`\`bash
npm install
npm run build
cp .env.example .env   # fill in credentials, or pass them via your MCP client config
npm start
\`\`\`

## Connect a client

Claude Code:

\`\`\`bash
claude mcp add ${slug} ${envFlags} -- node ${"$"}PWD/dist/server.js
\`\`\`

Claude Desktop (\`claude_desktop_config.json\`), Cursor (\`.cursor/mcp.json\`), Gemini CLI (\`~/.gemini/settings.json\`):

\`\`\`json
{
  "mcpServers": {
    "${slug}": {
      "command": "node",
      "args": ["/absolute/path/to/${slug}/dist/server.js"],
      "env": ${envJson}
    }
  }
}
\`\`\`

VS Code (\`.vscode/mcp.json\`): same object under \`"servers"\` with \`"type": "stdio"\`.

OpenAI Codex CLI (\`~/.codex/config.toml\`):

\`\`\`toml
[mcp_servers.${slug.replace(/-/g, "_")}]
command = "node"
args = ["/absolute/path/to/${slug}/dist/server.js"]
env = { ${envToml} }
\`\`\`

Regenerate with \`--target openai | gemini | cursor | bedrock | portable\` if a client rejects the tool schemas.

## Configuration

See \`.env.example\`. Useful switches: \`MCP_READ_ONLY=true\` exposes only GET tools, \`MCP_TOOLS_INCLUDE\` / \`MCP_TOOLS_EXCLUDE\` filter tools by name, tag or glob (handy for clients with tool limits), \`MCP_TRANSPORT=streamable-http\` serves \`http://localhost:3000/mcp\`.

Tool definitions live in \`tools.json\` and can be edited without rebuilding.
${webhookSection}
## Tools (${opts.tools.length})

| Tool | Endpoint | Summary |
|---|---|---|
${rows.join("\n")}
`;
}

function escapeCell(s: string): string {
	return s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}
