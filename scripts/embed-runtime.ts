// Embeds the generated-server runtime (src/runtime/*.ts) into
// src/generator/runtime-sources.ts so the published CLI can write it out
// without shipping loose files. Run after editing anything in src/runtime/.
//
//   bun scripts/embed-runtime.ts          write the file
//   bun scripts/embed-runtime.ts --check  exit 1 if it is stale

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export const RUNTIME_FILE_NAMES = ["types.ts", "validate.ts", "auth.ts", "http.ts", "webhooks.ts", "server.ts"];

const root = resolve(import.meta.dir, "..");
const target = join(root, "src", "generator", "runtime-sources.ts");

export function renderEmbedded(): string {
	const entries = RUNTIME_FILE_NAMES.map((name) => {
		const text = readFileSync(join(root, "src", "runtime", name), "utf-8").replace(/\r\n/g, "\n");
		return `\t${JSON.stringify(name)}: ${JSON.stringify(text)},`;
	});
	return `// AUTO-GENERATED by scripts/embed-runtime.ts from src/runtime/. Do not edit by hand.\n\nexport const RUNTIME_FILES: Record<string, string> = {\n${entries.join("\n")}\n};\n`;
}

if (import.meta.main) {
	const next = renderEmbedded();
	let current = "";
	try {
		current = readFileSync(target, "utf-8").replace(/\r\n/g, "\n");
	} catch {
		// first run
	}
	if (process.argv.includes("--check")) {
		if (current !== next) {
			console.error("src/generator/runtime-sources.ts is stale: run `bun scripts/embed-runtime.ts`");
			process.exit(1);
		}
	} else if (current !== next) {
		writeFileSync(target, next);
		console.log("Updated src/generator/runtime-sources.ts");
	}
}
